/** Node resolves a built half's bare `@abyme/cell` and services (`@abyme/<name>`, `/optional`,
* `/inventory`), which its build left for abymed, to the stand-ins. */
function hook() {
	if (hooked) return;
	hooked = true;
	const PREFIX = "abyme-contract:";
	registerHooks({
		resolve(specifier, context, next) {
			const from = context.parentURL?.split("?")[0];
			if (from && running.has(from) && /^@abyme\/[a-z0-9][a-z0-9_.-]*(\/optional|\/inventory)?$/.test(specifier)) return {
				url: `${PREFIX}${specifier}`,
				shortCircuit: true
			};
			return next(specifier, context);
		},
		load(url, context, next) {
			if (!url.startsWith(PREFIX)) return next(url, context);
			const specifier = url.slice(15);
			const m = /^@abyme\/([^/]+)(\/optional|\/inventory)?$/.exec(specifier);
			const now = m[1] === "cell" ? "globalThis.__abyme_contract.scope" : `globalThis.__abyme_contract.service(${JSON.stringify(m[1])})`;
			return {
				format: "module",
				source: `export default new Proxy(function () {}, { get: (_, k) => ${now}[k], has: (_, k) => k in ${now}, apply: (_, t, a) => Reflect.apply(${now}, t, a) });`,
				shortCircuit: true
			};
		}
	});
}
/** What a built half's `setup` answers, run against the stand-ins; refused after `ms`. */
async function run(file, ms) {
	const url = pathToFileURL(realpathSync(file)).href;
	running.add(url);
	const setup = (await import(`${url}?contract=${Date.now()}`)).default?.setup;
	if (typeof setup !== "function") throw new Error(`${file} is no built half: its default export has no setup`);
	let timer;
	const late = new Promise((_, reject) => {
		timer = setTimeout(() => reject(/* @__PURE__ */ new Error(`${file}'s setup did not answer in ${ms / 1e3} s against stand-ins`)), ms);
	});
	try {
		return await Promise.race([Promise.resolve(setup(globalThis.__abyme_contract.scope)), late]);
	} finally {
		clearTimeout(timer);
	}
}
