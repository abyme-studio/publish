/** A kind as `records.define` takes it, its schemas as JSON Schema. */
function kindOf(options) {
	const o = options ?? {};
	const spec = json(o.spec);
	const status = json(o.status);
	const actions = Object.entries(o.actions ?? {}).map(([name, a]) => {
		const args = json(a?.args);
		return [name, {
			...args && { args },
			...typeof a?.description === "string" && { description: a.description }
		}];
	});
	return {
		...spec && { spec },
		...status && { status },
		...actions.length > 0 && { actions: Object.fromEntries(actions) }
	};
}
