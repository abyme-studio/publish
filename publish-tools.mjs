/**
* The contract of a cell from its built halves (`server`, `machine`, each a file or null) and the
* services its manifest `provides`: each service's functions and stores, and every kind its halves
* define. Runs the halves' code in this process.
*/
async function contractOf(halves, provides, ms = 2e4) {
	hook();
	const kinds = {};
	const services = {};
	const add = (name, api) => {
		const defined = definedOf(api);
		if (!defined) return;
		const s = services[name] ??= {};
		for (const [fn, d] of Object.entries(defined.functions)) {
			const at = d.kind === "store" ? s.stores ??= {} : s.functions ??= {};
			at[fn] = memberOf(d);
		}
	};
	const { stand: s, api } = stand(kinds);
	globalThis.__abyme_contract = s;
	Object.defineProperty(globalThis, "__abyme_api", {
		value: api,
		configurable: true,
		writable: true
	});
	for (const file of [halves.server, halves.machine]) {
		if (!file) continue;
		const answered = await run(file, ms);
		if (provides.length === 1) add(provides[0], answered);
		else if (answered && typeof answered === "object") for (const name of provides) add(name, answered[name]);
	}
	return {
		services: sorted(services),
		kinds: sorted(kinds)
	};
}
